-- Champion trait profiles for the live-game build recommender.
-- One row per champion; `name` is the Data Dragon display name.

CREATE TYPE "public"."ChampionDurability" AS ENUM ('Squishy', 'Bruiser', 'Tanky');
CREATE TYPE "public"."ChampionShieldLevel" AS ENUM ('None', 'Low', 'High');
CREATE TYPE "public"."ChampionDamageType" AS ENUM ('AD', 'AP', 'Mixed');
CREATE TYPE "public"."ChampionThreatLevel" AS ENUM ('Low', 'Medium', 'High');
CREATE TYPE "public"."ChampionCcLevel" AS ENUM ('None', 'Low', 'Medium', 'High');

CREATE TABLE "public"."ChampionProfile" (
    "name" TEXT NOT NULL,
    "durability" "public"."ChampionDurability" NOT NULL,
    "shields" "public"."ChampionShieldLevel" NOT NULL,
    "damageType" "public"."ChampionDamageType" NOT NULL,
    "damageThreat" "public"."ChampionThreatLevel" NOT NULL,
    "cc" "public"."ChampionCcLevel" NOT NULL,
    "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "ChampionProfile_pkey" PRIMARY KEY ("name")
);

