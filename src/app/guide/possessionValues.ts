const POSSESSION_VALUE_BY_ID = new Map<string, number>(
  Object.entries(POSSESSION_VALUES).map(([name, value]) => [resolveChampionId(name), value])
);

export function possessionValueFor(champion: string): number | undefined {
  return POSSESSION_VALUE_BY_ID.get(resolveChampionId(champion));
}

export function possessionTierFor(value: number): PossessionTierListId | null {
  if (value >= 9) return "perfect";
  if (value >= 7) return "great";
  if (value >= 5) return "good";
  if (value >= 3) return "okay";
  if (value >= 1) return "useless";
  return null;
}
